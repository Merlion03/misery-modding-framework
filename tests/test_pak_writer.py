#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Tests for tools/content/pak_writer.py (plan.md task CT-01 -- write a UE 5.4
`.pak` v11 container with an unencrypted index).

Standard library only, and nothing here touches a game installation or a live
process: every test builds a container in memory, or in tmp_path, and inspects
the bytes.

The tests deliberately concentrate on the three places the format punishes a
careless writer silently -- the ones documented in the tool's own module
docstring, each of which produces a container that our own parsers accept and
the engine does not:

  1. the footer is SERIALISED in a different order than it is DECLARED
     (IPlatformFilePak.h:215-303 vs :193-201), so field-offset tests here are
     written against the serialise order and would fail loudly if someone
     "tidied" the writer into declaration order;
  2. the path-hash blob carries TWO structures -- the hash map AND a pruned
     directory index (PakFileUtilities.cpp:3175-3176) -- and omitting the
     second is invisible to pak_index.py and container_info.py, which SHA-1
     the blob without parsing it;
  3. v11's path hash is FNV-1a-64 with the seed ADDED to the offset basis
     (Fnv.cpp:26-42); versions below 11 transpose the two constants, and using
     the wrong pair yields a structurally perfect pak in which every lookup
     misses.

The reference numbers pinned below (byte sizes, the 0xE0000000 flag word, the
53-byte local header, the 221-byte footer) are not invented for the test: they
were confirmed against a container generated by this machine's own
UnrealPak.exe and against the shipped MISERY-Windows.pak, both v11 --
research/evidence/CT-05/.
"""

from __future__ import annotations

import hashlib
import os
import struct
import sys

import pytest

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO_ROOT, "tools", "content"))

import pak_writer as tool  # noqa: E402


# --------------------------------------------------------------------------- #
# FString -- String.cpp.inl:1873-1913
# --------------------------------------------------------------------------- #

def test_fstring_ansi_includes_terminator():
    # count is Data.Num(), i.e. Len() + 1, and the NUL is on the wire
    assert tool.fstring("abc") == struct.pack("<i", 4) + b"abc\x00"


def test_fstring_empty_is_four_zero_bytes():
    # NOT a count of 1 with a NUL: an empty FString has an empty Data array,
    # so Num() == 0 (String.cpp.inl:1906)
    assert tool.fstring("") == b"\x00\x00\x00\x00"


def test_fstring_non_ascii_switches_to_negative_count_utf16():
    out = tool.fstring("é")
    count = struct.unpack_from("<i", out, 0)[0]
    assert count == -2, "one char plus terminator, as UTF-16 code units"
    assert out[4:] == "é".encode("utf-16-le") + b"\x00\x00"


def test_fstring_mount_point_matches_shipped_container():
    # MISERY-Windows.pak's primary index begins with exactly these 14 bytes
    assert tool.fstring("../../../") == struct.pack("<i", 10) + b"../../../\x00"


# --------------------------------------------------------------------------- #
# the v11 path hash -- FFnv::MemFnv64 (Fnv.cpp:26-42), FPakFile::HashPath (C:6521)
# --------------------------------------------------------------------------- #

def test_fnv64_seed_is_added_to_the_offset_basis_not_xored():
    # The distinguishing property of the v11 ("Fnv64BugFix") variant.
    empty_seeded = tool.fnv64(b"", 5)
    assert empty_seeded == (tool.FNV64_OFFSET + 5) & tool.U64_MASK


def test_fnv64_matches_hand_computed_reference():
    h = (tool.FNV64_OFFSET + 0) & tool.U64_MASK
    for byte in b"a\x00":                      # 'a' as UTF-16LE
        h ^= byte
        h = (h * tool.FNV64_PRIME) & tool.U64_MASK
    assert tool.hash_path("a", 0) == h


def test_hash_path_lowercases_and_uses_utf16_without_terminator():
    assert tool.hash_path("ABC", 7) == tool.hash_path("abc", 7)
    assert tool.hash_path("abc", 7) == tool.fnv64("abc".encode("utf-16-le"), 7)
    # a terminator would change the result -- pin that it is absent
    assert tool.hash_path("abc", 7) != tool.fnv64("abc\x00".encode("utf-16-le"), 7)


def test_hash_path_is_seed_sensitive():
    assert tool.hash_path("x/y.txt", 1) != tool.hash_path("x/y.txt", 2)


def test_legacy_constant_pair_would_differ():
    """Guards the actual v11 bug fix: transposing offset and prime is exactly
    what versions < 11 did, and it still produces a plausible-looking hash."""
    legacy = 0x00000100000001B3
    swapped = ((legacy + 0) ^ ord("a")) & tool.U64_MASK
    swapped = (swapped * 0xCBF29CE484222325) & tool.U64_MASK
    assert tool.hash_path("a", 0) != swapped


