@pytest.fixture()
def built():
    return tool.build_pak(
        [("MISERY/Content/CT05/a.txt", b"alpha payload"),
         ("Engine/Content/CT05/b.txt", b"beta payload!!")],
        seed=0x1429B219)


def test_build_layout_tiles_the_file_exactly(built):
    layout = built["layout"]
    cursor = 0
    for key_off, key_size in (("index_offset", "index_size"),
                              ("path_hash_index_offset", "path_hash_index_size"),
                              ("full_directory_index_offset", "full_directory_index_size"),
                              ("footer_offset", "footer_size")):
        if key_off == "index_offset":
            assert layout[key_off] == layout["body_size"]
        else:
            assert layout[key_off] == cursor, key_off
        cursor = layout[key_off] + layout[key_size]
    assert cursor == layout["total_size"] == len(built["bytes"])


def test_build_reproduces_unrealpak_region_sizes(built):
    """Pinned against a container UnrealPak.exe generated from byte-identical
    input: body 133, primary 138, path-hash 32, full-dir 180, footer 221,
    total 704. A change in any of these means our layout diverged from Epic's."""
    layout = built["layout"]
    assert layout["body_size"] == 133
    assert layout["index_size"] == 138
    assert layout["path_hash_index_size"] == 32
    assert layout["full_directory_index_size"] == 180
    assert layout["footer_size"] == 221
    assert layout["total_size"] == 704


def test_footer_is_written_in_serialise_order_not_declaration_order(built):
    """The single easiest silent failure in this format. Footer discovery does
    not search for the magic -- it computes TotalSize - GetSerializedSize()
    (C:5989-6017) -- so a declaration-order footer is correctly sized and
    entirely wrong."""
    blob = built["bytes"]
    footer = blob[built["layout"]["footer_offset"]:]
    assert len(footer) == 221
    assert footer[0:16] == b"\x00" * 16                          # EncryptionKeyGuid
    assert footer[16] == 0                                       # bEncryptedIndex, 1 byte
    assert struct.unpack_from("<I", footer, 17)[0] == tool.PAK_MAGIC
    assert struct.unpack_from("<i", footer, 21)[0] == 11
    assert struct.unpack_from("<q", footer, 25)[0] == built["layout"]["index_offset"]
    assert struct.unpack_from("<q", footer, 33)[0] == built["layout"]["index_size"]
    assert footer[61:] == b"\x00" * 160                          # CompressionMethods


def test_footer_index_hash_covers_exactly_the_primary_index(built):
    blob = built["bytes"]
    layout = built["layout"]
    footer = blob[layout["footer_offset"]:]
    expected = hashlib.sha1(
        blob[layout["index_offset"]:layout["index_offset"] + layout["index_size"]]).digest()
    assert footer[41:61] == expected


def test_path_hash_blob_carries_the_pruned_directory_index_tail(built):
    """Trap 2: omitting this passes both project parsers and fails to mount,
    because C:6296 reads it in a Shipping build."""
    layout = built["layout"]
    blob = built["bytes"][layout["path_hash_index_offset"]:
                          layout["path_hash_index_offset"] + layout["path_hash_index_size"]]
    count = struct.unpack_from("<i", blob, 0)[0]
    assert count == 2
    consumed = 4 + count * 12
    assert len(blob) == consumed + 4, "an empty pruned index is exactly 4 more bytes"
    assert struct.unpack_from("<i", blob, consumed)[0] == 0


def test_keep_full_directory_in_pruned_slot_changes_only_that_blob():
    pruned = tool.build_pak([("A/x.txt", b"1")], seed=1, prune_directory_index=True)
    full = tool.build_pak([("A/x.txt", b"1")], seed=1, prune_directory_index=False)
    assert (full["layout"]["path_hash_index_size"]
            > pruned["layout"]["path_hash_index_size"])
    assert (full["layout"]["full_directory_index_size"]
            == pruned["layout"]["full_directory_index_size"])


def test_directory_index_contains_every_parent_including_root(built):
    directories = set(built["directory_index"])
    assert directories == {
        "/", "MISERY/", "MISERY/Content/", "MISERY/Content/CT05/",
        "Engine/", "Engine/Content/", "Engine/Content/CT05/"}


def test_every_path_resolves_through_the_path_hash_map(built):
    for directory, files in built["directory_index"].items():
        for filename, location in files.items():
            relative = filename if directory == "/" else directory + filename
            assert built["path_hash"][tool.hash_path(relative, built["seed"])] == location


def test_output_is_deterministic_for_a_fixed_seed():
    a = tool.build_pak([("A/x.txt", b"1"), ("B/y.txt", b"2")], seed=99)
    b = tool.build_pak([("A/x.txt", b"1"), ("B/y.txt", b"2")], seed=99)
    assert a["bytes"] == b["bytes"]


def test_self_test_passes_on_a_well_formed_container(built):
    for name, ok, detail in tool.self_test(built):
        assert ok, "%s failed: %s" % (name, detail)


