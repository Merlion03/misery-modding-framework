def test_local_header_is_53_bytes_for_v11_uncompressed():
    header = tool.local_header(5, 5, hashlib.sha1(b"hello").digest())
    assert len(header) == tool.LOCAL_HEADER_SIZE_V11 == 53


def test_local_header_offset_field_is_always_zero():
    """UnrealPak writes 0 here ('Don't serialize offsets here', U:1036) and
    stores the real offset only in the index (U:2750)."""
    header = tool.local_header(5, 5, b"\x11" * 20)
    assert struct.unpack_from("<q", header, 0)[0] == 0


def test_local_header_field_order_hash_before_flags():
    """Hash sits AFTER CompressionMethodIndex and BEFORE Flags -- not at the
    end of the record (H:495-544)."""
    sha = bytes(range(20))
    header = tool.local_header(5, 7, sha)
    assert struct.unpack_from("<q", header, 8)[0] == 5      # Size
    assert struct.unpack_from("<q", header, 16)[0] == 7     # UncompressedSize
    assert struct.unpack_from("<I", header, 24)[0] == 0     # method
    assert header[28:48] == sha
    assert header[48] == 0                                  # Flags
    assert struct.unpack_from("<I", header, 49)[0] == 0     # CompressionBlockSize


def test_local_header_rejects_wrong_hash_length():
    with pytest.raises(tool.PakWriteError):
        tool.local_header(1, 1, b"\x00" * 19)


def test_encoded_entry_is_twelve_bytes_with_the_expected_flag_word():
    """0xE0000000 == bits 31|30|29, method 0, unencrypted, zero blocks. This is
    the exact word our parser's census reports for both our containers and
    UnrealPak's own."""
    blob = tool.encode_entry(0, 5)
    assert len(blob) == 12
    assert struct.unpack_from("<I", blob, 0)[0] == 0xE0000000
    assert struct.unpack_from("<I", blob, 4)[0] == 0
    assert struct.unpack_from("<I", blob, 8)[0] == 5


def test_encoded_entry_omits_size_for_method_zero():
    """For method 0 the Size field is not emitted at all (C:7065); it is
    defined to equal UncompressedSize (C:7168-7170). Emitting it would shift
    every following byte while still parsing."""
    assert len(tool.encode_entry(10, 20)) == 12


def test_encoded_entry_refuses_oversized_fields_rather_than_truncating():
    with pytest.raises(tool.PakWriteError):
        tool.encode_entry(0x1_0000_0000, 5)


