def test_cli_writes_a_container_and_reports_layout(tmp_path):
    target = tmp_path / "cli.pak"
    rc = tool.main([str(target), "--add-literal", "hello=A/hello.txt"])
    assert rc == 0
    blob = target.read_bytes()
    assert len(blob) > 221
    footer = blob[-221:]
    assert struct.unpack_from("<I", footer, 17)[0] == tool.PAK_MAGIC


def test_cli_refuses_without_any_entries(tmp_path):
    assert tool.main([str(tmp_path / "empty.pak")]) == 2
